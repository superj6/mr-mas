const GL: Record<string, {w: number; rows: string[]}> = {};
for (const [k, v] of Object.entries(G)) { const rows = v.split('|'); GL[k] = {w: rows[0].length, rows}; }
export const OSD_CAP = 7;
const SP = 3, TR = 1;

export const osdWidth = (s: string) => {
  let w = 0;
  for (const ch of s.toUpperCase()) w += (ch === ' ' ? SP : (GL[ch]?.w ?? 4)) + TR;
  return Math.max(0, w - TR);
};
export const osdPlot = (s: string, x: number, y: number, p: Plot) => {
  let cx = x;
  for (const ch of s.toUpperCase()) {
    if (ch === ' ') { cx += SP + TR; continue; }
    const g = GL[ch];
    if (!g) { cx += 4 + TR; continue; }
    g.rows.forEach((r, j) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') p(cx + i, y + j); });
    cx += g.w + TR;
  }
};
/** OSD caps. `shadow` draws a 1 px drop shadow down-right (broadcast plates use it on bright fills). */
export const osdText = (b: Buf, s: string, x: number, y: number, col: number, shadow?: number) => {
  if (shadow !== undefined) osdPlot(s, x + 1, y + 1, b.ink(shadow));
  osdPlot(s, x, y, b.ink(col));
};
