export const BIT_W = 5;
export const BIT_H = 9;
export const BIT_ADV = 6;
/** Returns on-pixels [x,y] for a string, origin top-left of the ascender line. */
export const bitText = (s: string, adv = BIT_ADV): [number, number][] => {
  const out: [number, number][] = [];
  [...s].forEach((ch, i) => {
    const g = G[ch] ?? G[' '];
    g.split(' ').forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push([i * adv + x, y]);
    });
  });
  return out;
};
export const bitWidth = (s: string, adv = BIT_ADV) => [...s].length * adv - 1;
